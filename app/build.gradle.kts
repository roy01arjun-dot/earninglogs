android {
  namespace = "com.example"
  compileSdk { version = release(36) { minorApiLevel = 1 } }

  defaultConfig {
    // Must stay in sync with google-services.json - the Firebase Android app and its OAuth
    // client are registered against this exact id. Changing it breaks Google sign-in.
    applicationId = "com.aistudio.workhourstracker.pxmkzq"
    minSdk = 24
    targetSdk = 36
    // Play rejects an upload whose versionCode is not greater than the previous one.
    versionCode = 2
    versionName = "2.0"

    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
  }

  // Upload-key credentials come from keystore.properties (gitignored) or the environment,
  // so no password is ever committed. See RELEASE.md for how to create the key.
  val keystorePropsFile = rootProject.file("keystore.properties")
  val keystoreProps = Properties()
  if (keystorePropsFile.exists()) {
    FileInputStream(keystorePropsFile).use { stream -> keystoreProps.load(stream) }
  }
  val releaseStorePath: String? = keystoreProps.getProperty("storeFile")
    ?: System.getenv("KEYSTORE_PATH")
  val hasReleaseKeystore = releaseStorePath != null && file(releaseStorePath).exists()

  signingConfigs {
    if (hasReleaseKeystore) {
      create("release") {
        storeFile = file(releaseStorePath!!)
        storePassword = keystoreProps.getProperty("storePassword") ?: System.getenv("STORE_PASSWORD")
        keyAlias = keystoreProps.getProperty("keyAlias") ?: System.getenv("KEY_ALIAS") ?: "upload"
        keyPassword = keystoreProps.getProperty("keyPassword") ?: System.getenv("KEY_PASSWORD")
      }
    }
    create("debugConfig") {
      storeFile = file("${rootDir}/debug.keystore")
      storePassword = "android"
      keyAlias = "androiddebugkey"
      keyPassword = "android"
    }
  }

  buildTypes {
    release {
      isCrunchPngs = true
      isMinifyEnabled = true
      isShrinkResources = true
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      // Falls back to an unsigned build rather than failing configuration when the upload key
      // is absent (fresh clone, CI without secrets). The previous config hardcoded a path to a
      // my-upload-key.jks that does not exist, so `assembleRelease` could never run at all.
      signingConfig = if (hasReleaseKeystore) signingConfigs.getByName("release") else null
    }
    debug { signingConfig = signingConfigs.getByName("debugConfig") }
  }
  compileOptions {
    sourceCompatibility = JavaVersion.VERSION_11
    targetCompatibility = JavaVersion.VERSION_11
  }
  buildFeatures {
    compose = true
    buildConfig = true
  }
  testOptions { unitTests { isIncludeAndroidResources = true } }
}

